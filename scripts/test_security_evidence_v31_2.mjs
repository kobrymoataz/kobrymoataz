assert(!scanExpr.findings.some(x=>x.rule==='http-cleartext'||x.rule==='http-tls-verification'||x.title==='Retrying potentially non-idempotent request'));
assert.equal(scanExpr.coverage.unknownDynamicUrls,1);
const localhost=structuredClone(expr);localhost.nodes[1].parameters.url='http://localhost:8080/hello';
assert(inspectSecurity(localhost).findings.some(x=>x.rule==='http-cleartext'&&x.severity==='info'));
const disabled=structuredClone(edited);disabled.nodes[1].disabled=true;assert.equal(inspectSecurity(disabled).findings.length,0);
const trust={schema:'trustops-audit-v1',domain:'example.org',partial:true,finishedAt:'2026-10-25',counts:{pass:3,warn:1,fail:0,unknown:2},evidence:[{secret:'CANARY-DNS-SECRET'}]};
