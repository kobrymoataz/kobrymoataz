assert(report.delta.new.some(x=>x.title==='Retrying potentially non-idempotent request'));
assert(report.delta.resolved.some(x=>x.title==='HTTP request retry disabled'));
assert.equal(report.execution.failedRuns,2);
assert(!JSON.stringify(report).includes('CANARY-CREDENTIAL-SECRET'));
assert(!JSON.stringify(report).includes('CANARY-URL-SECRET'));
assert(!JSON.stringify(report).includes('CANARY-EXECUTION-SECRET'));
assert(!JSON.stringify(report).includes('Send to API'));
assert(!JSON.stringify(report).includes('http-1'));
