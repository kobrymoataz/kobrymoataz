assert.equal(supTrust.counts.pass,3);assert.equal(supTrust.partial,true);
assert(!JSON.stringify(supTrust).includes('CANARY-DNS-SECRET'));
const repo={version:'30.2',repository:'owner/repo',finishedAt:'2026-10-25',checks:[{status:'observed'},{status:'advisory'},{status:'unknown'}],coverage:['tree checked'],raw:[{secret:'CANARY-REPO-SECRET'}]};
const supRepo=importSupplement(JSON.stringify(repo));assert.equal(supRepo.counts.unknown,1);
assert(!JSON.stringify(supRepo).includes('CANARY-REPO-SECRET'));
