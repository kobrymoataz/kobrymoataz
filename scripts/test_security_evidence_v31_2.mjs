import assert from 'node:assert/strict';
import {webcrypto} from 'node:crypto';
import {createSampleWorkflow,analyzeWorkflow,updateNodeReliability} from '../docs/automation-core.mjs';
import {inspectSecurity,importSupplement,findingDelta,buildEvidencePack,evidenceHtml} from '../docs/security-evidence-core.mjs';
if(!globalThis.crypto)globalThis.crypto=webcrypto;
const sample=createSampleWorkflow();
const edited=structuredClone(sample);
const http=edited.nodes.find(n=>n.type.endsWith('.httpRequest'));
