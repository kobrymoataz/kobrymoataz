http.retryOnFail=true;
const scan=inspectSecurity(edited);
assert(scan.findings.some(x=>x.rule==='http-cleartext'&&x.severity==='warning'));
assert(scan.findings.some(x=>x.rule==='http-tls-verification'));
assert(scan.findings.some(x=>x.title==='Retrying potentially non-idempotent request'));
assert.equal(scan.counts.warning,3);
assert(!JSON.stringify(scan).includes('CANARY-CREDENTIAL-SECRET'));
assert(!JSON.stringify(scan).includes('CANARY-URL-SECRET'));
const expr=structuredClone(edited);expr.nodes[1].parameters.url='={{ $json.targetUrl }}';expr.nodes[1].parameters.options.ignoreSSLIssues=false;expr.nodes[1].parameters.method='GET';
